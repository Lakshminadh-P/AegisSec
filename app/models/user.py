"""
User Model

Stores user accounts with role-based access control (RBAC).
Roles: ADMIN, SECURITY_ANALYST, DEVELOPER

Security Notes:
- Passwords are NEVER stored in plaintext — only bcrypt hashes
- Role-based access prevents unauthorized actions
"""
from sqlalchemy import Column, Integer, String, Boolean, DateTime
from sqlalchemy.sql import func
from app.database import Base


class User(Base):
    __tablename__ = "users"

    id = Column(Integer, primary_key=True, index=True)
    username = Column(String(50), unique=True, index=True, nullable=False)
    email = Column(String(100), unique=True, index=True, nullable=False)
    hashed_password = Column(String(255), nullable=False)
    role = Column(String(20), default="DEVELOPER", nullable=False)
    is_active = Column(Boolean, default=True)
    created_at = Column(DateTime(timezone=True), server_default=func.now())
    updated_at = Column(DateTime(timezone=True), onupdate=func.now())
